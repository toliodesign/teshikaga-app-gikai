#!/usr/bin/env python3
"""説明欄の読み取りの検査。失敗したら自動更新を止める（おかしなデータを公開しないため）。"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from update import parse_description as P, time_check as C, parse_questions as Q, classify as K, _cmd, VID_RE

D = "\n********************\n公式チャンネルです。0:00 これは無視される"
def times(d): return [x[0] for x in P(d)[2]]

# A 議案の動画：時刻＋件名、同じ時刻にまとまる続きの行
assert times("4:45 行政報告\n15:28 報告第6号 A\n19:25 議案第62号 B\n議案第63号 C\n議案第64号 D" + D) == ["4:45","15:28","19:25","19:25","19:25"]
# B 一般質問：時刻（質問番号）を残し、質問事項・要旨も読む
q, g, i = P("0:25 質問番号5\n【質問事項】\nヒグマ対策\n\n【質問要旨】\n昨年に引き続き\nまた" + D)
assert i == [["0:25", "質問番号5"]] and q == "ヒグマ対策" and g.startswith("昨年") and "\n" in g
# C 全角の時刻  D 括弧つき  E 時刻だけの行  F 質問要旨のあとの時刻
assert times("４：４５ 行政報告\n１５：２８ 報告" + D) == ["4:45", "15:28"]
assert times("【4:45】行政報告\n[15:28] 報告" + D) == ["4:45", "15:28"]
assert P("4:45\n行政報告" + D)[2] == [["4:45", "行政報告"]]
assert times("0:25 質問番号5\n【質問事項】\nX\n【質問要旨】\n要旨\n20:10 再質問" + D) == ["0:25", "20:10"]
# G 文末の時刻は読めないので、見落としの疑いとして必ず知らせる
assert C("行政報告 4:45\n報告 15:28" + D) == (2, 0)
# 1時間をこえる時刻、「********」より下は無視、予算説明の注記は目次にしない
assert times("1:02:03 議案" + D) == ["1:02:03"]
assert P("4:12 予算説明\n\n※予算書は町ホームページ\nhttps://example.jp\n" + D)[2] == [["4:12", "予算説明"]]
assert C("4:45 A\n15:28 B" + D) == (2, 2)
# H 本物の説明欄（行の途中の時刻「（45:57　質疑）」を含む）。見落とし警告の数も合うこと
real = ("1:54          令和7年度弟子屈町一般会計補正予算について（45:57　質疑）\n"
        "1:42:58    令和7年度弟子屈町介護保険特別会計補正予算について" + D)
assert P(real)[2] == [["1:54", "令和7年度弟子屈町一般会計補正予算について（45:57　質疑）"],
                      ["1:42:58", "令和7年度弟子屈町介護保険特別会計補正予算について"]]
assert C(real) == (3, 3)
assert P("1:54 A（４５：５７　質疑）" + D)[2] == [["1:54", "A（45:57　質疑）"]]   # 全角の途中の時刻
# I 質問が2つ入った一般質問（質問番号7・8）：質問ごとに分かれ、混ざらないこと
two = ("0:20 質問番号7\n【質問事項】\n弟子屈高校の今後へ向けた方向性について\n\n【質問要旨】\n2028年度の公立高校配置計画において、\n①今現在の高校への支援の進捗\n②今後の動き\n上記2点について伺う。\n\n"
       "22:24 質問番号8\n【質問事項】\n中心市街地複合施設における計画の継続について\n\n【質問要旨】\n6月議会の総括質疑時に\n理事者の考えを伺う。" + D)
b = Q(two)
assert [x["time"] for x in b] == ["0:20", "22:24"] and [x["label"] for x in b] == ["質問番号7", "質問番号8"]
assert b[0]["q"] == "弟子屈高校の今後へ向けた方向性について" and b[1]["q"] == "中心市街地複合施設における計画の継続について"
assert b[0]["gist"].startswith("2028年度") and b[0]["gist"].endswith("伺う。") and "中心市街地" not in b[0]["gist"]
assert b[1]["gist"] == "6月議会の総括質疑時に\n理事者の考えを伺う。" and C(two) == (2, 2)
# J 質問が1つ／時刻のない質問／議案の動画（質問なし）
assert len(Q("0:25 質問番号5\n【質問事項】\nヒグマ\n【質問要旨】\n要旨" + D)) == 1
nt = Q("【質問事項】\nA\n【質問要旨】\nB\n【質問事項】\nC" + D)
assert [(x["time"], x["q"]) for x in nt] == [("", "A"), ("", "C")]
assert all(not (x["q"] or x["gist"]) for x in Q("4:45 行政報告\n15:28 議案" + D))
# K 動画の種類（上から順に最初に合った種類。どれにも合わなければ「その他」）
assert K("令和8年第2回定例会1日目（6/2火）⑤　一般質問（萩原議員）") == "一般質問"
assert K("令和7年第4回定例会2日目（12/3水）⑦　令和7年度会計補正予算・予算特別委員会") == "予算特別委員会"
assert K("令和7年第3回定例会1日目（9/8月）①　開会～議案第72号（財産の取得について）") == "議案の審議"
assert K("令和7年第4回定例会2日目（12/3水）⑧　予算特別委員長報告～閉会") == "その他"
new = [{"name": "決算特別委員会", "title": ["決算特別委員"]}] + [{"name": "一般質問", "title": ["一般質問"]}]   # 新しい種類は、1行足すだけ
assert K("令和7年第3回定例会3日目（9/10水）② 決算特別委員会（総括質疑）", new) == "決算特別委員会"
assert K("令和7年第3回定例会3日目 ③ 一般質問（板垣議員）", new) == "一般質問" and K("何かの動画", new) == "その他"
# L 実行記録の安全化と、動画IDの形
assert _cmd("a%b\nc\r") == "a%25b%0Ac%0D" and VID_RE.match("2o8cvswguvc") and not VID_RE.match('x" onmouseover="')
print("読み取りの検査：すべて合格")
